using System;
using System.Collections.Generic;
using UnityEngine;

namespace DeckParty
{
    /// <summary>Named polish moments. Each one maps to a Feel feedback prefab in the <see cref="FxLibrary"/>.</summary>
    public enum FxCue
    {
        ViewerJoined = 0,
        DiamondJoined = 1,
        CardHover = 2,
        ButtonPress = 3,
        ButtonDenied = 4,
        AbilityUsed = 5,
        ImpactRecruit = 6,
        ImpactRemove = 7,
        ImpactModify = 8,
        ImpactShuffle = 9,
        ImpactScout = 10,
        ImpactEconomy = 11,
        CounterPunch = 12,
        RiskPip = 13,
        SubCapFull = 14,
        DiamondTracker = 15,
        Deplatform = 16,
        ServerDown = 17,
        ScoreTick = 18,
        Victory = 19,
        Defeat = 20,
        TurnBanner = 21,
        BoardSwitch = 22,
        BannerSlam = 23,
        ToastIn = 24,
        MenuIn = 25,
        StreamerAnxious = 26,
        PowerUsed = 27,
        Purchase = 28,
        Stamp = 29,
        ScreenShake = 30,
        SelectConfirm = 31,
    }

    /// <summary>
    /// Every tunable bit of polish in one asset (Resources database > fx). Generated by Deck Party > Setup; nothing in it
    /// is overwritten afterwards unless you run Deck Party > FX > Rebuild FX (overwrites).
    ///  - Cues: which Feel feedback prefab plays for each moment, its strength, and an on/off switch.
    ///  - Materials: Sprite Shaders Ultimate "uber" materials for cards and portraits (status effects fade in and out).
    ///  - Polish switches: the nice-to-have features, each one independently.
    /// </summary>
    [CreateAssetMenu(menuName = "Deck Party/FX Library", fileName = "FxLibrary")]
    public sealed class FxLibrary : ScriptableObject
    {
        [Serializable]
        public sealed class CueEntry
        {
            [HideInInspector] public string name;
            public FxCue cue;
            [Tooltip("A prefab with an MMF_Player (Feel). Its feedbacks target their parent, so it works on any card or panel.")]
            public GameObject feedback;
            [Range(0f, 2f)] public float intensity = 1f;
            public bool enabled = true;
        }

        /// <summary>Which revision of the generated Feel recipes this library's prefabs were built with (see FeelFxBuilder).</summary>
        [HideInInspector] public int recipeRevision;

        [Header("Global")]
        [Tooltip("Multiplies every Feel duration (the Fast Animations setting halves it on top).")]
        [Range(0.25f, 3f)] public float durationMultiplier = 1f;
        [Tooltip("Multiplies every shake (players also have a Screen Shake slider).")]
        [Range(0f, 2f)] public float shakeMultiplier = 1f;

        [Header("Moments")]
        public List<CueEntry> cues = new List<CueEntry>();

        [Header("Sprite Shaders Ultimate")]
        [Tooltip("Card portrait material (SSU GUI uber). Each card gets its own instance; effects fade in and out by property.")]
        public Material portraitUber;
        [Tooltip("Material for buttons and panels that shine (End the Stream at 4 Diamonds, the title...).")]
        public Material shineUber;

        [Header("Core polish")]
        public bool statusEffects = true;
        public bool scoringSequence = true;
        public bool presenceSignals = true;
        public bool streamerAnxiety = true;

        [Header("Nice-to-haves")]
        [Tooltip("N1: signature effects and stamps for every viewer action and arrival special.")]
        public bool signatureEffects = true;
        [Tooltip("N4: LIVE badge and stream timer on the board.")]
        public bool streamOverlay = true;
        [Tooltip("N5: emotes players can send (they pop up from the sender's avatar on every screen).")]
        public bool emotes = true;
        [Tooltip("Viewers in chat send emojis that float up (art in the Game Database > Viewer Emojis).")]
        public bool viewerEmojis = true;
        [Tooltip("Multiplayer text chat (lobby and game). Off: players talk with emotes only. The chat code is kept for future modes.")]
        public bool textChat = false;
        [Tooltip("N6: watchers see the active player's mouse pointer.")]
        public bool ghostCursor = true;
        [Tooltip("N7: cards tilt slightly toward the cursor.")]
        public bool cardTilt = true;
        [Tooltip("N8: static portraits breathe gently so un-animated characters feel alive.")]
        public bool idleBreathing = true;
        [Tooltip("N9: background lights react to Deplatform Risk.")]
        public bool reactiveBackground = true;
        [Tooltip("N10: shine and glitch on the title, animated menu background.")]
        public bool shinyTitle = true;
        [Tooltip("N11: music ducks under big moments and goes muffled while a menu is open.")]
        public bool audioJuice = true;
        [Tooltip("N12: hover ticks rise in pitch across a row of cards.")]
        public bool musicalHover = true;
        [Tooltip("N13: comic stamps (BONK!, NOPE., U MAD?).")]
        public bool comicStamps = true;
        [Tooltip("N14: link lines between attached partners and along Nyan Cat chains.")]
        public bool linkLines = true;

        static FxLibrary s_Default;

        /// <summary>The library from the Game Database, or built-in defaults (everything on) when none is assigned.</summary>
        public static FxLibrary Current
        {
            get
            {
                var fx = GameDatabase.Instance.fx;
                if (fx != null) return fx;
                if (s_Default == null)
                {
                    s_Default = CreateInstance<FxLibrary>();
                    s_Default.hideFlags = HideFlags.DontSave;
                }
                return s_Default;
            }
        }

        public CueEntry Get(FxCue cue)
        {
            foreach (var entry in cues)
                if (entry != null && entry.cue == cue) return entry;
            return null;
        }

        public void EnsureAllCues()
        {
            foreach (FxCue cue in Enum.GetValues(typeof(FxCue)))
            {
                var entry = Get(cue);
                if (entry == null) cues.Add(entry = new CueEntry { cue = cue });
                entry.name = cue.ToString();
            }
            cues.Sort((a, b) => a.cue.CompareTo(b.cue));
        }

        void OnValidate()
        {
            foreach (var entry in cues)
                if (entry != null) entry.name = entry.cue.ToString();
        }
    }
}
